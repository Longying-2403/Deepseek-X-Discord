    if cards:
        what.append("说过话的人现在的人设卡")
        # 私信里（有私信记忆）：敏感的事就算他要求也不进人设卡（人设卡服务器里会用到），记进私信记忆
        rule = REVIEW_CARDS_SENSITIVE_DM if dm else REVIEW_CARDS_SENSITIVE
        parts.append(REVIEW_CARDS.format(card_max=card_max, sensitive=rule))
        schema["cards"] = '[{"to": 他自己那条消息的编号, "name": "他的名字", "text": "改好之后完整的人设卡"}]'
    if memory:
        what.append("这个服务器现在的长期记忆" if group is None else "组里现在共用的长期记忆")
        # 记满了（或者超过上限）、里面又有别的服务器记的：它只能删自己的，别逼它为了腾地方删（没连组、全是自己记的，照常合并、删旧的）
        if foreign and count > max_entries:
            fullness = REVIEW_MEMORY_OVER
        elif foreign and count >= max_entries:
            fullness = REVIEW_MEMORY_FULL
        else:
            fullness = REVIEW_MEMORY_ROOM
        fullness = fullness.format(count=count, max_entries=max_entries)
        parts.append(REVIEW_MEMORY.format(entry_max=entry_max, fullness=fullness))
        if foreign:
            parts.append(REVIEW_MEMORY_FOREIGN.format(n=foreign))
        schema["memory"] = '[{"add": "新的一条"}, {"edit": 编号, "text": "改好的内容"}, {"delete": 编号}]'
    if group is not None and (cards or memory):
        parts.append((REVIEW_GROUP_SHARED if shared is not None else REVIEW_GROUP).format(guild=group))
    elif shared is not None and cards:
        parts.append(REVIEW_SHARED.format(guild=shared))
    if dm_memory:
        what.append("他的私信记忆")
        where = REVIEW_DM_WHERE_CARDS if cards else REVIEW_DM_WHERE_NO_CARDS
        parts.append(REVIEW_DM_MEMORY.format(entry_max=dm_entry_max, count=dm_count, max_entries=dm_max_entries, where=where))
        schema["dm_memory"] = (
            '[{"add": "新的一条", "sensitive": true 或 false}, {"edit": 编号, "text": "改好的内容", "sensitive": true 或 false}, {"delete": 编号}]'
        )
    shape = "{" + ", ".join(f'"{k}": {v}' for k, v in schema.items()) + "}"
    empty = "{" + ", ".join(f'"{k}": []' for k in schema) + "}"
    return REVIEW_SYSTEM.format(
        name=name,
        what=("，还有" + "和".join(what)) if what else "",
        parts=(REVIEW_DM if dm else "") + "".join(parts),
        schema=shape,
        empty=empty,
    )
