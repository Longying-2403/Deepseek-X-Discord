def clean_persona(text: str) -> str:
    """人设正文：去掉首尾空白，以及模型照抄过来的 <人设> 标签（标签是我们用来框住人设的）。"""
    return text.replace("<人设>", "").replace("</人设>", "").strip()


def _listing(text: str, more: int) -> str:
    if not text:
        return f"有 {more} 个，没列出来" if more else "没有"
    return text + (f"（还有 {more} 个没列出来）" if more else "")


def build_system_prompt(
    *,
    guild: str,
    channel: str,
    name: str,
    persona: str,
    summary: str | None,
    search: bool = False,
    share: bool = False,
    emojis: Sequence[str] = (),
    stickers: Sequence[str] = (),
    more_emojis: int = 0,
    more_stickers: int = 0,
    memes: Sequence[str] = (),
    more_memes: int = 0,
    images: bool = False,
    links: str = "off",
    cards: Sequence[str] | None = None,
    more_cards: int = 0,
    cards_elsewhere: int = 0,
    cards_shared: bool = False,
    memories: Sequence[tuple[int, str]] | None = None,
    memory_max: int = 50,
    card_max: int = 1600,
    entry_max: int = 200,
    music: bool = False,
    remind: bool = True,
    dm_with: str | None = None,
    desktop: Sequence[str] | None = None,
    dm_memories: Sequence[tuple[int, str, bool]] | None = None,
    dm_memory_max: int = 150,
    dm_entry_max: int = 200,
    dm_memory_more: int = 0,
    group: Sequence[str] | None = None,
    memory_foreign: int = 0,
    memory_more: int = 0,
    shared_notes: Sequence[tuple[str, str]] = (),
    sync: Sequence[str] | None = None,
    sync_here: str | None = None,
    sync_past: str | None = None,
    sync_foreign: bool = False,
    sync_cards: bool = True,
) -> str:
    """固定的规则在前（同一个服务器的所有频道共用，缓存命中），会变的部分放在后面。
    group：和这个服务器连成一组的别的服务器的名字（None = 不在组里）。
    memory_foreign：长期记忆里有几条是组里别的服务器记的（记满了时别为了腾地方删）。
    memory_more：长期记忆太多、没列出来的几条（比较早的；条数、记没记满按全部的算）。
    shared_notes：群友自己标成可共享的私信记忆 [(名字, 内容)]（服务器的频道里才有）。
    sync：和这个频道连通的别的频道（「服务器」#频道；None = 没连通）；sync_here：这个频道在记录里的写法；
    sync_past：这个频道连通之前自己的记录（摘要和最后几行，只给这个频道看）；sync_foreign：连通的频道不全在同一个服务器；
    sync_cards：那样连通时人设卡照样能附、能改（所有服务器共用一张，或者这里没开人设卡）。

    emojis / stickers / memes：这个服务器里能用的表情名、贴图名、表情包名（调用方已经排好序、截好数量）；
    more_* 是没列出来的个数。images：能不能上网找图。links：打开链接的能力（all / x / off）。
    cards：有人设卡的人的名字（None = 这里没开人设卡）；cards_elsewhere：卡里有别的服务器的人时（连成一组、所有服务器共用），
    没在这个服务器出现过、有卡的人数（只看有没有）。cards_shared：所有服务器共用一张人设卡（config.toml 的 [bot] shared_cards）。
    memories：长期记忆 [(编号, 内容)]（None = 没开）。
    music：能不能点歌（bot 开了点歌、装好了要用的东西）。remind：能不能设提醒（/dsadmin 设置 参数:提醒）。dm_with：私信时对方的名字（guild 是私信挂在的那个服务器）。
    dm_memories：私信时他的私信记忆 [(编号, 内容, 敏感)]（None = 不是私信，或者没开私信记忆）；dm_memory_more：太多了没列出来的几条。
    """
    persona = clean_persona(persona or "") or DEFAULT_PERSONA
    shared = cards_shared and cards is not None  # 这里开了人设卡，卡又是所有服务器共用的
    if dm_with is not None:
        text = SYSTEM_RULES + IDENTITY_DM.format(
            user=dm_with,
            guild=guild,
            name=name,
            persona=persona,
            whose=IDENTITY_DM_WHOSE_SHARED if shared else IDENTITY_DM_WHOSE,
            card_reach=IDENTITY_DM_CARD_REACH_SHARED if shared else "",
        )
    else:
        text = SYSTEM_RULES + IDENTITY.format(guild=guild, channel=channel, name=name, persona=persona)
    where = "开了记忆共享，能翻记录的频道写在聊天记录里" if share else "这里没开记忆共享，看不到别的频道"
    text += TOOLS_BLOCK.format(
        search="能用" if search else "这里不能用",
        channels=where,
        emojis=_listing(" ".join(f":{e}:" for e in emojis), more_emojis),
        stickers=_listing("、".join(stickers), more_stickers),
        memes=_listing("、".join(memes), more_memes),
        images="能用" if images else "这里不能用",
        links=LINKS_MODES.get(links, LINKS_MODES["off"]),
        cards=_cards_line(cards, more_cards, card_max, cards_elsewhere, shared=shared),
        memory="这里没开"
        if memories is None
        else f"能用，在最后面「长期记忆」里（现在 {len(memories) + memory_more} 条，最多 {memory_max} 条，每条最多 {entry_max} 字）"
        + (
            MEMORY_OVER
            if len(memories) + memory_more > memory_max and group
            else MEMORY_FULL
            if len(memories) + memory_more >= memory_max and group and memory_foreign
            else ""
        ),
        music="能用（只能放 B站的视频，不放直播）" if music else "这里不能用",
        remind="能用" if remind else "这里没开",
    )
    if group:
        shares = GROUP_SHARES_NO_CARDS if cards_shared else GROUP_SHARES
        text += GROUP_BLOCK.format(others="、".join(f"「{g}」" for g in group), shares=shares)
    if sync is not None:
        text += SYNC_BLOCK.format(
            here=sync_here or f"#{channel}",
            others="、".join(sync) or "别的频道",
            foreign=(SYNC_FOREIGN + ("" if sync_cards else SYNC_FOREIGN_CARDS)) if sync_foreign else "",
        )
    if shared:
        text += CARDS_SHARED_BLOCK
    if memories is not None:
        entries = "\n".join(f"({no}) {entry}" for no, entry in memories) or "（还没有）"
        if memory_more:
            entries += "\n" + MEMORY_MORE.format(n=memory_more)
        text += (MEMORY_BLOCK_GROUP if group else MEMORY_BLOCK).format(entries=entries)
    if shared_notes:
        text += SHARED_NOTES_BLOCK.format(entries="\n".join(f"- {who}：{entry}" for who, entry in shared_notes))
    if dm_memories is not None and dm_with is not None:
        lines = "\n".join(f"({no}) {entry}" + ("〔敏感〕" if sensitive else "") for no, entry, sensitive in dm_memories)
        text += DM_MEMORY_BLOCK.format(
            user=dm_with,
            entries=lines or "（还没有）",
            count=len(dm_memories) + dm_memory_more,
            max_entries=dm_memory_max,
            entry_max=dm_entry_max,
            more=f"比较早的 {dm_memory_more} 条没列在这里。" if dm_memory_more else "",
            where=DM_MEMORY_WHERE_CARDS if cards is not None else DM_MEMORY_WHERE_NO_CARDS,
        )
    if desktop is not None:
        text += DESKTOP_BLOCK.format(apps="、".join(desktop) or "还没有（电脑上的小程序还没连上过）")
    if sync is not None and sync_past:
        text += SYNC_PAST_BLOCK.format(past=sync_past.strip())
    if summary:
        text += (SUMMARY_BLOCK_SYNC if sync is not None else SUMMARY_BLOCK).format(summary=summary.strip())
    return text


def _cards_line(cards: Sequence[str] | None, more: int, card_max: int, elsewhere: int = 0, *, shared: bool = False) -> str:
    if cards is None:
        return "这里没开"
    head = f"能用（所有服务器共用，每人一张，每张最多 {card_max} 字）" if shared else f"能用（每张最多 {card_max} 字）"
    # 卡里有别的服务器的人时：他们不列名字（可能和这里的人同名），聊到时按名字查，查到的会写明不在这里。
    # 只说有，不说几个：别处多一张卡，这里的提示词（缓存）不用跟着变
    tail = "；另外还有人有卡，没在这里的频道出现过（聊到时也能按名字查）" if elsewhere else ""
    if not cards and not more:
        return head + ("，这里还没有人有卡" if elsewhere else "，现在还没有人有卡") + tail
    return head + "，有卡的人：" + _listing("、".join(cards), more) + tail


